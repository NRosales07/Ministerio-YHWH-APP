import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
const sourceDirectory = join(root, 'piano-src');
const outputPath = join(root, 'piano.js');
const parts = [
  '00-runtime-and-state.js',
  '05-instrument-runtime.js',
  '10-song-library.js',
  '20-metronome.js',
  '30-track-selection-and-timeline.js',
  '40-player-visuals-and-settings.js',
  '50-drum-pad-and-audio-cache.js',
  '60-instruments-and-playback.js',
  '70-recording-auth-and-events.js',
  '80-offline-firebase-device-settings.js',
  '90-instrument-download-library.js',
];

const contents = await Promise.all(parts.map(async (name) => {
  const content = await readFile(join(sourceDirectory, name), 'utf8');
  if (!content.trim()) throw new Error(`La parte ${name} está vacía.`);
  return content;
}));

const bundle = [
  '// Generated by build-piano.mjs from piano-src/*.js. Edit the source parts, not this file.\n',
  ...contents,
].join('');

await writeFile(outputPath, bundle, 'utf8');
console.log(`piano.js generado desde ${parts.length} partes.`);
